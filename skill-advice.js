function skillAdviceHtml(jobKey, skillName) {
  const job = (typeof SKILL_ADVICE !== "undefined" && SKILL_ADVICE[jobKey]) || null;
  if (!job) return "";
  const a = job[skillName];
  if (!a) return "";
  const esc = function (s) { return String(s).replace(/[&<>"]/g, function (c) { return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]; }); };
  const bits = [];
  if (a.tag === "必修" || a.tag === "選修") {
    bits.push('<span class="adv-tag ' + (a.tag === "必修" ? "adv-must" : "adv-opt") + '">' + esc(a.tag) + "</span>");
    if (a.points != null) bits.push('<span class="adv-pts">建議 ' + a.points + " 點</span>");
  } else {
    bits.push('<span class="adv-tag adv-note">簡評</span>');
  }
  if (a.reason) bits.push('<span class="adv-why" title="' + esc(a.reason) + '">' + esc(a.reason) + "</span>");
  return bits.join("");
}
